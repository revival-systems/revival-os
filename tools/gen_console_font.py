#!/usr/bin/env python3
"""gen_console_font.py - turn the console's glyph art into its Rust table.

Reads boot/samsung-serranolte/console/font.txt (the single source of the 5x7
glyphs for ASCII 0x20 to 0x7E) and produces boot/samsung-serranolte/console/
font.rs, the table the console image is built from. font.rs is committed, so a
build never runs this tool; `make test-console` runs it with --check and fails
if font.rs is not exactly what font.txt gives.

Each glyph row becomes one byte whose bit 4 is the leftmost pixel and bit 0 the
rightmost. The host oracle (tests/boot/console_v2.py) does not use this tool or
font.rs: it reads font.txt itself, so a mistake here shows up as a framebuffer
that differs from the oracle.

Usage: gen_console_font.py [--check | --write]   (default: --check)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "boot/samsung-serranolte/console/font.txt"
RUST = ROOT / "boot/samsung-serranolte/console/font.rs"

FIRST_CODE = 0x20
LAST_CODE = 0x7E
COLS = 5
ROWS = 7


def parse_art(text: str) -> dict[int, list[str]]:
    """The glyphs in font.txt, as {character code: seven rows of '#' and '.'}.
    Raises ValueError, naming the line, on anything the format does not allow."""
    glyphs: dict[int, list[str]] = {}
    code = None
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.rstrip()
        if not line or line.startswith(";"):
            continue
        if line.startswith("@"):
            if code is not None and len(glyphs[code]) != ROWS:
                raise ValueError(f"line {number}: glyph {code:#04x} has "
                                 f"{len(glyphs[code])} rows, want {ROWS}")
            try:
                code = int(line[1:].strip(), 16)
            except ValueError:
                raise ValueError(f"line {number}: bad glyph header {line!r}") from None
            if code in glyphs:
                raise ValueError(f"line {number}: glyph {code:#04x} is defined twice")
            glyphs[code] = []
            continue
        if code is None:
            raise ValueError(f"line {number}: a row before any glyph header")
        if len(line) != COLS or set(line) - {"#", "."}:
            raise ValueError(f"line {number}: a row must be {COLS} cells of '#' or '.'")
        if len(glyphs[code]) == ROWS:
            raise ValueError(f"line {number}: glyph {code:#04x} has more than {ROWS} rows")
        glyphs[code].append(line)
    if code is not None and len(glyphs[code]) != ROWS:
        raise ValueError(f"glyph {code:#04x} has {len(glyphs[code])} rows, want {ROWS}")
    want = list(range(FIRST_CODE, LAST_CODE + 1))
    if sorted(glyphs) != want:
        raise ValueError(f"font.txt must define exactly the codes {FIRST_CODE:#04x} "
                         f"to {LAST_CODE:#04x}, once each")
    return glyphs


def row_byte(row: str) -> int:
    """One glyph row as a byte: bit 4 is the leftmost pixel."""
    value = 0
    for cell in row:
        value = (value << 1) | (cell == "#")
    return value


def rust_source(glyphs: dict[int, list[str]]) -> str:
    lines = [
        "//! font.rs - GENERATED by tools/gen_console_font.py from font.txt. Do not edit.",
        "//!",
        "//! The console's own 5x7 glyphs for ASCII 0x20 to 0x7E (drawn for Revival OS,",
        "//! no third-party font data). To change a glyph, edit font.txt and run",
        "//! `python3 -I tools/gen_console_font.py --write`; `make test-console` fails",
        "//! if this file and font.txt disagree.",
        "//!",
        "//! One byte per glyph row, top row first. Bit 4 is the leftmost pixel and",
        "//! bit 0 the rightmost; bits 5 to 7 are zero.",
        "",
        "/// Character code of the first glyph in `GLYPHS`.",
        f"pub const FIRST_CODE: u8 = 0x{FIRST_CODE:02X};",
        "/// Character code of the last glyph in `GLYPHS`.",
        f"pub const LAST_CODE: u8 = 0x{LAST_CODE:02X};",
        "/// Pixels across one glyph.",
        f"pub const GLYPH_COLS: usize = {COLS};",
        "/// Pixels down one glyph.",
        f"pub const GLYPH_ROWS: usize = {ROWS};",
        "/// Number of glyphs: one for each code from `FIRST_CODE` to `LAST_CODE`.",
        f"pub const GLYPH_COUNT: usize = {LAST_CODE - FIRST_CODE + 1};",
        "",
        "pub static GLYPHS: [[u8; GLYPH_ROWS]; GLYPH_COUNT] = [",
    ]
    for code in range(FIRST_CODE, LAST_CODE + 1):
        rows = ", ".join(f"0x{row_byte(row):02X}" for row in glyphs[code])
        lines.append(f"    [{rows}], // 0x{code:02X} {chr(code)}".rstrip())
    lines += ["];", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true",
                       help="fail if font.rs is not what font.txt gives (default)")
    group.add_argument("--write", action="store_true", help="rewrite font.rs")
    args = parser.parse_args(argv)
    try:
        want = rust_source(parse_art(ART.read_text(encoding="ascii")))
    except (OSError, ValueError) as exc:
        print(f"gen_console_font: {exc}", file=sys.stderr)
        return 1
    if args.write:
        RUST.write_text(want, encoding="ascii")
        print(f"wrote {RUST.relative_to(ROOT)}")
        return 0
    try:
        have = RUST.read_text(encoding="ascii")
    except OSError as exc:
        print(f"gen_console_font: {exc}", file=sys.stderr)
        return 1
    if have != want:
        print("gen_console_font: font.rs is not what font.txt gives; run "
              "python3 -I tools/gen_console_font.py --write", file=sys.stderr)
        return 1
    print("OK font.rs matches font.txt (95 glyphs)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
